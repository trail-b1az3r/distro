"""Package manifests: what each profile and the live ISO install, written to
packages/manifests/ so changes show up in code review.

    python3 -m distrokit.build.manifests          # rewrite packages/manifests/
    python3 -m distrokit.build.manifests --check  # exit 1 if they are stale

Per-machine additions (kernel choice, microcode, GPU drivers, laptop and VM
tools, the boot loader) are listed separately in hardware.txt, because the
installer adds them from the hardware report.
"""

from __future__ import annotations

import argparse
import sys
import tomllib
from pathlib import Path

from .. import paths
from ..branding import Branding, load as load_branding
from ..profiles import load_features, load_profiles, read_list, select_packages


def profile_manifest(b: Branding, profile_id: str) -> str:
    profile = load_profiles()[profile_id]
    sel = select_packages(profile, branding=b)
    feats = load_features()
    lines = [f"# {b.pretty_name}: {profile.name} profile (generated by distrokit.build.manifests; do not edit)",
             f"# {profile.summary}",
             "# features: " + ", ".join(f"{k}={v}" for k, v in sorted(sel.features.items()) if k in feats),
             f"# {len(sel.packages)} packages, plus the hardware-dependent ones in hardware.txt", ""]
    by_source: dict[str, list[str]] = {}
    for pkg in sel.packages:
        by_source.setdefault(sel.reasons.get(pkg, "other"), []).append(pkg)
    for source in sorted(by_source):
        lines.append(f"## {source}")
        lines += sorted(by_source[source])
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def live_manifest(b: Branding) -> str:
    from .iso import LIVE_EXTRA, LIVE_LISTS, live_packages

    pk = live_packages(b)
    return (f"# {b.pretty_name}: live ISO (packages.x86_64; generated, do not edit)\n"
            f"# lists: {', '.join(LIVE_LISTS)} + {', '.join(LIVE_EXTRA)}\n# {len(pk)} packages\n\n"
            + "\n".join(sorted(pk)) + "\n")


def hardware_manifest(b: Branding) -> str:
    root = paths.DATA_ROOT
    with (root / "hardware" / "gpu" / "drivers.toml").open("rb") as fh:
        drivers = tomllib.load(fh)
    out = [f"# {b.pretty_name}: packages the installer adds per machine (generated, do not edit)", ""]
    out += ["## every machine: kernel(s) chosen in the installer, CPU microcode",
            "linux (or linux-lts, linux-zen; +headers when DKMS modules are used)", "amd-ucode | intel-ucode", ""]
    out += ["## graphics: common", *drivers["common"]["packages"],
            "(multilib) " + " ".join(drivers["common"].get("packages_32bit", [])), ""]
    for sid, stack in sorted(drivers["stack"].items()):
        out.append(f"## graphics: {sid} — {stack['label']} ({stack.get('source', 'repo')})")
        out += stack.get("packages", [])
        if stack.get("packages_32bit"):
            out.append("(multilib) " + " ".join(stack["packages_32bit"]))
        if stack.get("compute"):
            out.append("(GPU compute) " + " ".join(stack["compute"]))
        if stack.get("prebuilt"):
            out.append("(prebuilt modules) " + ", ".join(f"{k}: {v}" for k, v in stack["prebuilt"].items()))
        out.append("")
    for name in ("grub", "laptop", "intel-laptop", "virt-qemu", "virt-virtualbox", "virt-vmware", "virt-hyperv"):
        out.append(f"## {name}")
        out += read_list(name, b)
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def manifests(b: Branding | None = None) -> dict[str, str]:
    b = b or load_branding()
    files = {f"{pid}.txt": profile_manifest(b, pid) for pid in load_profiles()}
    files["live.txt"] = live_manifest(b)
    files["hardware.txt"] = hardware_manifest(b)
    return files


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Write or check packages/manifests/.")
    p.add_argument("--check", action="store_true")
    a = p.parse_args(argv)
    out_dir = paths.DATA_ROOT / "packages" / "manifests"
    stale = []
    for name, text in manifests().items():
        path = out_dir / name
        if a.check:
            if not path.is_file() or path.read_text() != text:
                stale.append(name)
        else:
            out_dir.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if stale:
        print("stale manifests: " + ", ".join(stale) + " (run python3 -m distrokit.build.manifests)", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
