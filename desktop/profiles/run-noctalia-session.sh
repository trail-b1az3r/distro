#!/usr/bin/env bash
# Noctalia's SDDM session: keep Halcyon's Lua config and Quickshell startup untouched.
set -Eeuo pipefail

config="${XDG_CONFIG_HOME:-$HOME/.config}/hypr/frontline-noctalia.lua"
mkdir -p "$(dirname "$config")"
if [[ ! -e "$config" ]]; then
    cat > "$config" <<'LUA'
-- Minimal Hyprland-plus session dedicated to Noctalia Shell.
hl.config({ autogenerated = false })
hl.on("hyprland.start", function()
    hl.exec_cmd("noctalia")
end)
hl.bind("SUPER + Space", hl.dsp.exec_cmd("noctalia msg panel-toggle launcher"))
hl.bind("SUPER + Return", hl.dsp.exec_cmd("alacritty"))
hl.bind("SUPER + Comma", hl.dsp.exec_cmd("noctalia msg settings-toggle"))
hl.bind("SUPER + Q", hl.dsp.exec_cmd("hyprctl dispatch exit"))
LUA
fi

if command -v start-hyprland >/dev/null 2>&1; then
    exec start-hyprland -- --config "$config" "$@"
fi
exec Hyprland --config "$config" "$@"
