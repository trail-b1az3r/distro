#!/usr/bin/env bash
# The login entry of an extra desktop (ML4W, HyDE, SekaiPop): Hyprland with that desktop's own home
# (profile-home.sh), so its configuration, and anything it writes, never mixes with Halcyon's.
set -Eeuo pipefail

profile="${1:-}"
case "$profile" in ml4w|hyde|sekaipop|work|macshell|frameshell|paperrice) ;; *) echo "Unknown desktop profile: $profile" >&2; exit 2 ;; esac
shift || true

REAL_HOME="${REAL_HOME:-$HOME}"
SCRIPT_DIR="$(cd -- "$(dirname -- "$(readlink -f -- "${BASH_SOURCE[0]}")")" && pwd)"
# shellcheck source=profile-home.sh
. "$SCRIPT_DIR/profile-home.sh"

home="$(profile_home "$profile")"
if [[ ! -d "$home" && ! -d "$PROFILE_ROOT/configs/$profile" ]]; then
    echo "$profile is not installed. Install it with distro-install-desktop-profiles $profile." >&2
    exit 1
fi
profile_home_setup "$profile"
profile_env "$profile"
cd "$HOME"

# PaperRice ships a legacy hyprland.conf, but Nexora's Hyprland 0.57 session is Lua-only.
# Keep its Quickshell config and run it on a minimal Lua compositor session instead.
if [[ "$profile" == paperrice && -f "$home/.config/quickshell/paper/shell.qml" ]]; then
    runtime="${XDG_RUNTIME_DIR:-/run/user/$(id -u)}"
    session="$runtime/distro-paper-rice-hyprland.lua"
    cat > "$session" <<'LUA'
hl.config({ autogenerated = false })
hl.on("hyprland.start", function()
    hl.exec_cmd("quickshell -p ~/.config/quickshell/paper/shell.qml")
end)
LUA
    if command -v start-hyprland >/dev/null; then
        exec start-hyprland -- --config "$session" "$@"
    fi
    exec Hyprland --config "$session" "$@"
fi

# No configuration of its own (an install that did not finish, or one made before Hyprland read only hyprland.lua):
# Hyprland would open its own example instead of the desktop. Open a small session that says so and installs the
# desktop again, in a terminal; the installer runs as it does from Halcyon, with the real home.
if ! profile_config_ok "$profile"; then
    problem="$(profile_config_problem "$profile")"
    runtime="${XDG_RUNTIME_DIR:-/run/user/$(id -u)}"
    repair="$runtime/distro-desktop-repair-$profile"
    mkdir -p "$repair"
    terminal=""
    for candidate in alacritty kitty foot konsole xterm; do
        if command -v "$candidate" >/dev/null; then terminal="$candidate"; break; fi
    done
    cat > "$repair/repair.sh" <<REPAIR
#!/usr/bin/env bash
echo "The $profile desktop is not set up: $problem."
echo "Installing it again in its own home. Halcyon is not changed."
echo
distro-install-desktop-profiles $profile <<< y
echo
read -r -p "Press Enter to log out, then choose $profile on the login screen again. " _
hyprctl dispatch 'hl.dsp.exit()' >/dev/null 2>&1 || hyprctl dispatch exit >/dev/null 2>&1
REPAIR
    chmod +x "$repair/repair.sh"
    cat > "$repair/hyprland.lua" <<LUA
-- Written by distro-desktop-session: the $profile desktop has no configuration of its own yet.
hl.config({ autogenerated = false })
hl.bind("SUPER + Q", hl.dsp.exec_cmd("$terminal"))
hl.bind("SUPER + M", hl.dsp.exec_cmd("hyprctl dispatch 'hl.dsp.exit()'"))
hl.on("hyprland.start", function()
    hl.exec_cmd("$terminal -e $repair/repair.sh")
end)
LUA
    echo "$profile has no configuration of its own ($problem): starting the repair session." >&2
    if command -v start-hyprland >/dev/null; then
        exec start-hyprland -- --config "$repair/hyprland.lua"
    fi
    exec Hyprland --config "$repair/hyprland.lua"
fi

# A preview of this desktop for the login screen's desktop switcher: a small screenshot a few seconds after it starts
# (before apps are open), in the shared previews folder. Off with ~/.config/nexora/no-session-preview (in the real
# home).
previews=/var/lib/nexora/session-previews
if [[ -d "$previews" && -w "$previews" && ! -e "$REAL_HOME/.config/nexora/no-session-preview" ]] && command -v grim >/dev/null; then
    (
        runtime="${XDG_RUNTIME_DIR:-/run/user/$(id -u)}"
        before="$(ls "$runtime"/wayland-* 2>/dev/null | grep -v '\.lock$' || true)"
        socket=""
        for _ in {1..30}; do
            sleep 1
            socket="$(ls "$runtime"/wayland-* 2>/dev/null | grep -v '\.lock$' | grep -vxF -- "$before" | head -n1 || true)"
            [[ -n "$socket" ]] && break
        done
        [[ -n "$socket" ]] || exit 0
        sleep 8
        WAYLAND_DISPLAY="$(basename "$socket")" grim -s 0.5 -t png "$previews/.nexora-$profile.png.tmp" 2>/dev/null \
            && mv -f "$previews/.nexora-$profile.png.tmp" "$previews/nexora-$profile.png" \
            && chmod 0644 "$previews/nexora-$profile.png"
    ) &
fi

# The user's systemd and D-Bus services follow the session's environment while it runs (desktops export it); set
# the real home back for them when it ends, so the next Halcyon session's services are Halcyon's.
# dconf (where gsettings are kept: GTK theme, icons, cursor, dark mode) is a user service that reads its file from
# the home it was started with; it is stopped at each change, so the next gsettings start it in the right home.
reset_services() {
    systemctl --user unset-environment XDG_CONFIG_HOME XDG_DATA_HOME XDG_STATE_HOME XDG_CACHE_HOME 2>/dev/null || true
    systemctl --user set-environment HOME="$REAL_HOME" 2>/dev/null || true
    dbus-update-activation-environment --systemd HOME="$REAL_HOME" 2>/dev/null || true
    systemctl --user stop dconf.service 2>/dev/null || true
}
trap reset_services EXIT

cd "$HOME"
# The user's services run in this desktop's home from the start (its settings, not Halcyon's).
systemctl --user set-environment HOME="$HOME" XDG_CONFIG_HOME="$XDG_CONFIG_HOME" XDG_DATA_HOME="$XDG_DATA_HOME" \
    XDG_STATE_HOME="$XDG_STATE_HOME" XDG_CACHE_HOME="$XDG_CACHE_HOME" 2>/dev/null || true
dbus-update-activation-environment --systemd HOME XDG_CONFIG_HOME XDG_DATA_HOME XDG_STATE_HOME XDG_CACHE_HOME \
    2>/dev/null || true
systemctl --user stop dconf.service 2>/dev/null || true
# start-hyprland (Hyprland 0.57+) watches Hyprland and is how a login manager should start it.
if command -v start-hyprland >/dev/null; then
    if (( $# )); then start-hyprland -- "$@"; else start-hyprland; fi
else
    Hyprland "$@"
fi
